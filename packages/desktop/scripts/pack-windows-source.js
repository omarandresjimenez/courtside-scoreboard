// Packs the source tree into a zip you can carry to a Windows machine and
// build the NSIS installer from (`npm run dist:win`), because cross-building
// it from macOS is deliberately blocked — see require-windows-build-host.js.
//
// What goes in is decided by git, not by a hand-maintained list:
// `git ls-files --cached --others --exclude-standard` is every file in the
// working tree that isn't gitignored. That already excludes node_modules/,
// packages/desktop/release/, packages/client/dist/, packages/server/generated/,
// *.db and .env, while still picking up files that are new and not yet
// committed. Those excluded artifacts are all regenerated on the Windows side
// by the steps in the WINDOWS-BUILD.md this script writes into the zip.
//
// Usage: node scripts/pack-windows-source.js [outputDir]
//        (defaults to the current user's Downloads folder)

const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const repoRoot = path.resolve(__dirname, '..', '..', '..');
const { version } = require(path.join(repoRoot, 'packages', 'desktop', 'package.json'));

const outputDir = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(os.homedir(), 'Downloads');
const stem = `courtside-scoreboard-windows-build-${version}`;
const zipPath = path.join(outputDir, `${stem}.zip`);

// A top-level folder inside the zip, so extracting on Windows can't scatter
// files across whatever directory Explorer happened to be pointed at.
const staging = fs.mkdtempSync(path.join(os.tmpdir(), 'courtside-winpack-'));
const stageRoot = path.join(staging, stem);

function gitFiles() {
  const out = execFileSync(
    'git',
    ['ls-files', '--cached', '--others', '--exclude-standard', '-z'],
    {
      cwd: repoRoot,
      maxBuffer: 64 * 1024 * 1024,
    },
  );
  return out
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .filter((f) => path.basename(f) !== '.DS_Store');
}

const WINDOWS_BUILD_DOC = `# Building the Courtside Scoreboard Windows installer

This zip is the project source with build artifacts stripped out. Everything
removed is regenerated by the steps below.

## Requirements

- Windows 10 or 11, x64
- Node.js 20 or newer (https://nodejs.org — the LTS installer is fine)
- An internet connection for \`npm install\` (only for the build; the app
  itself never needs internet at match time)

## Build

Open PowerShell in this folder and run, in order:

\`\`\`powershell
npm install
npm run build --workspace packages/client
npx prisma generate --schema=packages/server/prisma/schema.prisma
npm run dist:win --workspace packages/desktop
\`\`\`

Each step matters:

1. \`npm install\` restores dependencies for all four workspace packages.
2. \`build --workspace packages/client\` produces \`packages/client/dist\`,
   which the installer bundles as the UI it serves.
3. \`prisma generate\` produces \`packages/server/generated\`, including the
   \`query_engine-windows.dll.node\` binary the packaged server loads. This
   directory is gitignored and is NOT in this zip — the build fails without
   this step.
4. \`dist:win\` regenerates the empty template database, prunes the server's
   dependencies to production-only, and runs electron-builder.

The installer is written to:

\`\`\`
packages\\desktop\\release\\Courtside Scoreboard Setup ${version}.exe
\`\`\`

## After building

\`dist:win\` replaces \`packages/server/node_modules\` with a production-only
tree. If you want to run the tests or typechecks in this copy afterwards, run
\`npm install\` again first.

## Installing it

The installer is not code-signed, so Windows SmartScreen will warn on first
run. Choose **More info**, then **Run anyway**. Removing that warning requires
a Windows code-signing certificate.

## What the app does on first launch

It generates a random admin password, copies a blank pre-migrated SQLite
database into the user's app-data folder, starts the bundled server on port
3000, and shows a small launcher window with the machine's LAN address. Other
devices on the same Wi-Fi reach it at \`http://<that-address>:3000\`.
`;

try {
  const files = gitFiles();
  if (files.length === 0) throw new Error('git listed no files to pack — is this a git repo?');

  for (const rel of files) {
    const src = path.join(repoRoot, rel);
    // ls-files can name a path that was deleted from disk but is still staged.
    if (!fs.existsSync(src)) continue;
    const dest = path.join(stageRoot, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(src, dest);
  }

  fs.writeFileSync(path.join(stageRoot, 'WINDOWS-BUILD.md'), WINDOWS_BUILD_DOC);

  fs.mkdirSync(outputDir, { recursive: true });
  fs.rmSync(zipPath, { force: true });

  if (process.platform === 'win32') {
    execFileSync(
      'powershell',
      [
        '-NoProfile',
        '-Command',
        `Compress-Archive -Path "${stageRoot}" -DestinationPath "${zipPath}"`,
      ],
      { stdio: 'inherit' },
    );
  } else {
    // -X drops the macOS extra attributes that would otherwise show up as
    // __MACOSX/ and ._ junk files when unzipped on Windows.
    execFileSync('zip', ['-r', '-q', '-X', zipPath, stem], { cwd: staging, stdio: 'inherit' });
  }

  const { size } = fs.statSync(zipPath);
  console.log(`Packed ${files.length + 1} files (${(size / 1024 / 1024).toFixed(1)} MB)`);
  console.log(zipPath);
} finally {
  fs.rmSync(staging, { recursive: true, force: true });
}
